"""
Algorithm-to-behaviour map of the 41 algorithms (research document 8.2: "do not claim the result of the architecture as proof of all 41 at once").

The table is generated from the pipeline's own registry (`rct_control_plane/algorithm_pipeline.ADAPTERS`: id, name, stage, whether it calls a model, the network or writes) plus a small hand-written part that
says which algorithms the governed loop uses DIRECTLY (not only as a pipeline stage) and which removal switch exists today. For each algorithm it answers four questions:

  channel        how can it change what the agent does? `direct` (the loop's own code), `advice` (a pre-episode stage whose output lines are put in the prompt as labelled data), `record` (a post-episode stage:
                 it records, verifies or learns after the answer, so it cannot change THIS episode's decisions)
  behaviour      what that change could be, in a word
  removal today  the switch that removes it, if one exists (none for most: the pipeline is all-or-nothing)
  what an ablation could show   stated by the channel: an `advice` or `record` algorithm cannot move a scripted model's decision, and a live test of it needs a model that reads advice

Run `python -m research.algorithm_map` to regenerate `research/ALGORITHM_BEHAVIOUR_MAP.md`; a test fails when the file and the registry disagree.
"""
from __future__ import annotations

from pathlib import Path
from typing import Dict, List

DIRECT = {
    "ALGO-01": ("the numeric FDIA gate on risky tools", "switch F (DAAES D2): `A101`"),
    "ALGO-04": ("the RCT-7 plan in the prompt and the end check", "switch R (DAAES D1): `A011`"),
    "ALGO-21": ("FAST goals capped at 3 steps, SLOW keep the budget", "`route=False` in a session (no DAAES arm yet)"),
    "ALGO-25": ("DeltaBlock log, history compression, versioned log", "storage arm of TC-009/TC-025 (full snapshots)"),
    "ALGO-07": ("per-person graded growth (MEE) that decides what is learned", "none"),
}
BEHAVIOUR = {"understand": "what the agent is told about the goal", "recall": "which memories and facts it is offered", "plan": "how work is split, routed or scheduled", "act": "how a tool behaves when the agent calls it",
             "verify": "what is accepted as learned after the answer", "compress": "what is stored or sent in fewer bytes", "record": "what is written down for audit", "evolve": "what the system adds to itself"}
PIPELINE_SWITCH = "`DELENTIA_ALGORITHM_PIPELINE=0` removes every pre-episode advice stage at once (no per-algorithm switch)"


def rows() -> List[Dict[str, str]]:
    from rct_control_plane.algorithm_pipeline import ADAPTERS
    out: List[Dict[str, str]] = []
    for a in ADAPTERS:
        direct = DIRECT.get(a.algo_id)
        channel = "direct" if direct else ("advice" if a.phase == "pre" else "record")
        flags = [f for f, on in (("model", a.llm), ("network", a.network), ("writes", a.writes)) if on]
        out.append({"id": a.algo_id, "name": a.name, "stage": a.stage, "phase": a.phase, "channel": channel, "behaviour": direct[0] if direct else BEHAVIOUR.get(a.stage, "-"),
                    "removal": direct[1] if direct else (PIPELINE_SWITCH if channel == "advice" else "none (a post-episode stage)"), "flags": ", ".join(flags) or "-"})
    return out


def render() -> str:
    data = rows()
    ids = sorted({r["id"] for r in data})
    by_channel = {c: sorted({r["id"] for r in data if r["channel"] == c}) for c in ("direct", "advice", "record")}
    lines = ["# Algorithm-to-behaviour map of the 41 algorithms", "",
             "Generated by `python -m research.algorithm_map` from the pipeline's own registry; do not edit by hand. Research document 8.2 warns against reading a whole-architecture result as proof of 41 algorithms at once:",
             "this map says, per algorithm, how it could change an episode at all and what removing it would show.", "",
             f"{len(ids)} algorithms ({len(data)} registry entries: ALGO-06, ALGO-10 and ALGO-34 have two roles each). Direct in the loop: {len(by_channel['direct'])} ({', '.join(by_channel['direct'])}). "
             f"Pre-episode advice stages: {len(by_channel['advice'])}. Post-episode record/verify/learn stages: {len(by_channel['record'])}.", "",
             "What this means for a test. For an `advice` algorithm the only road to a decision is a model that READS the advice line in its prompt, so a scripted model cannot show an effect and a live test needs a model that "
             "reads and uses it. A `record` algorithm acts after the answer and cannot change the decisions of the episode it follows. Only the `direct` ones have a removal switch that changes the loop itself.", "",
             "| algorithm | name | stage | channel | what it can change | removal today | uses |", "|---|---|---|---|---|---|---|"]
    for r in sorted(data, key=lambda x: (x["id"], x["stage"])):
        lines.append(f"| {r['id']} | {r['name']} | {r['stage']} ({r['phase']}) | {r['channel']} | {r['behaviour']} | {r['removal']} | {r['flags']} |")
    lines += ["", "What exists as evidence today (Round 64 audit, `research/main_objects_audit.json`): every algorithm RUNS on real input (25 of 41 on two real goals, 37 of 41 with fixtures) and leaves a trace; none has an A/B showing it HELPS with a capable model."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(__file__).with_name("ALGORITHM_BEHAVIOUR_MAP.md").write_text(render(), encoding="utf-8")
    print(f"{len({r['id'] for r in rows()})} algorithms written")
