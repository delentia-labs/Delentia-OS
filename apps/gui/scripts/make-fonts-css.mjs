// Round 106: writes src/app/fonts.css, the @font-face rules for the three fonts the Architect chose (Prompt, JetBrains Mono, Sarabun), read from the @fontsource packages in node_modules.
// Why not next/font/google: that downloads the fonts while the Desk is BUILT, and a failed download on a CI runner fails the whole build (it showed up as a Turbopack "module not found"; the
// release and Package check jobs then fail for a reason that has nothing to do with the code). The packages are fetched by `npm ci` with the rest, which is cached and checked against the lockfile.
// Run:  node scripts/make-fonts-css.mjs   (the result is committed; a test checks it matches what this script would write)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "..", "src", "app", "fonts.css");

const THAI = "U+02D7,U+0303,U+0331,U+0E01-0E5B,U+200C-200D,U+25CC";
const LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";

const FAMILIES = [
  { family: "Prompt", pkg: "prompt", file: "prompt", weights: [300, 400, 500, 600], subsets: ["thai", "latin"] },
  { family: "Sarabun", pkg: "sarabun", file: "sarabun", weights: [400, 500, 600], subsets: ["thai", "latin"] },
  { family: "JetBrains Mono", pkg: "jetbrains-mono", file: "jetbrains-mono", weights: [400, 500, 600], subsets: ["latin"] },
];

export function render() {
  const out = ["/* Generated by scripts/make-fonts-css.mjs (Round 106). Do not edit by hand. Fonts: Prompt, Sarabun, JetBrains Mono (SIL Open Font License 1.1), from the @fontsource packages. */"];
  for (const f of FAMILIES) {
    for (const subset of f.subsets) {
      for (const weight of f.weights) {
        const file = `${f.file}-${subset}-${weight}-normal.woff2`;
        const full = path.join(here, "..", "node_modules", "@fontsource", f.pkg, "files", file);
        if (!fs.existsSync(full)) throw new Error(`missing ${full}: run npm ci`);
        out.push(`@font-face {\n  font-family: "${f.family}";\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${weight};\n  src: url("../../node_modules/@fontsource/${f.pkg}/files/${file}") format("woff2");\n  unicode-range: ${subset === "thai" ? THAI : LATIN};\n}`);
      }
    }
  }
  return out.join("\n") + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, render());
  console.log("wrote", OUT);
}
