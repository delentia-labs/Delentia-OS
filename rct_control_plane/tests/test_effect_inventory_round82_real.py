"""
Round 82, plan item T05: the effect inventory (research/EFFECT_INVENTORY.md, generated by research/effect_inventory.py) cannot drift from the code, and its hand-written labels cannot
contradict the sets the governed loop really enforces.

The labels are the one thing a person writes. These tests cross-check them: a tool that writes a file must always need a signature; a tool with any side effect must be gated once the
episode has read outside text; a tool labelled harmless must be one the loop treats as inert; and the gateway that is NOT mediated by the loop is named in the page.
"""
import sys, os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from pathlib import Path

from research import effect_inventory as inv
from rct_control_plane import governed_autonomous_loop as g

ROOT = Path(__file__).resolve().parent.parent.parent
NAMES = inv.tool_names()


def test_every_exposed_tool_has_an_entry_and_every_entry_names_a_real_tool():
    assert [n for n in NAMES if n not in inv.EFFECTS] == [], "a tool with no entry in research/effect_inventory.py: decide what it can do, then add it"
    assert [n for n in inv.EFFECTS if n not in NAMES] == []


def test_effect_labels_come_from_the_fixed_vocabulary():
    vocabulary = {inv.READ, inv.COMPUTE, inv.OUTSIDE, inv.EGRESS, inv.LOCAL_WRITE, inv.ARTIFACT, inv.CODE, inv.SCHEDULE, inv.DELEGATE, inv.MEMORY, inv.STATE, inv.EXCHANGE}
    assert {effect for effect, _ in inv.EFFECTS.values()} <= vocabulary
    assert all(touches.strip() for _, touches in inv.EFFECTS.values())


def test_a_tool_that_writes_a_workspace_file_always_needs_a_signature():
    writers = {n for n, (effect, _) in inv.EFFECTS.items() if effect == inv.LOCAL_WRITE}
    assert writers == {"delentia_write_repo_file", "delentia_patch_repo_file"}
    assert writers <= g._ALWAYS_NEEDS_APPROVAL_TOOLS


def test_every_tool_with_a_side_effect_is_gated_once_the_episode_has_read_outside_text():
    for name, (effect, _) in inv.EFFECTS.items():
        if effect in inv.SIDE_EFFECT and effect != inv.EGRESS:
            assert name in g.TAINT_GATED_TOOLS, f"{name} is labelled {effect} but the taint gate does not hold it"
    egress = {n for n, (effect, _) in inv.EFFECTS.items() if effect == inv.EGRESS}
    assert egress == set(g.TAINT_EGRESS_TOOLS)                                                   # the tools that open an address are exactly the ones whose address is restricted


def test_text_from_outside_is_a_taint_source_and_a_harmless_label_is_one_the_loop_treats_as_inert():
    for name, (effect, _) in inv.EFFECTS.items():
        if effect == inv.OUTSIDE:
            assert name in g.TAINT_SOURCE_TOOLS, name
        if effect in inv.INERT_OK:
            assert name in g.TAINT_INERT_TOOLS, f"{name} is labelled {effect} but the loop does not list it as inert"
    for name in g.TAINT_INERT_TOOLS:
        assert inv.EFFECTS[name][0] in inv.INERT_OK, f"{name} is inert in the loop but labelled {inv.EFFECTS[name][0]}"


def test_the_generated_page_is_up_to_date_and_names_the_surface_outside_the_loop():
    page = (ROOT / "research" / "EFFECT_INVENTORY.md").read_text(encoding="utf-8")
    assert page.replace("\r\n", "\n") == inv.render(), "run: python research/effect_inventory.py"
    assert "NOT mediated by the governed loop" in page and "delentia_execute_safe_shell" in page and "no signed approval" in page
    assert "## 4. Not covered" in page and "Root on the host" in page


def test_the_gateway_tools_listed_in_the_page_are_the_gateway_tools_that_exist():
    import re
    source = (ROOT / "rct_control_plane" / "mcp_gateway.py").read_text(encoding="utf-8")
    real = set(re.findall(r'"name": "(delentia_[a-z_]+)"', source))
    assert {name for name, _ in inv.GATEWAY_TOOLS} == real


def test_host_check_tells_the_owner_about_the_surface_outside_the_loop(monkeypatch):
    from rct_control_plane import host_check
    monkeypatch.delenv("DELENTIA_API_TOKENS_FILE", raising=False)
    checks = host_check.check_raw_gateway()
    assert len(checks) == 1 and checks[0].id == "H24" and checks[0].status == host_check.INFO
    assert "outside the governed loop" in checks[0].detail and "EFFECT_INVENTORY.md" in checks[0].detail
